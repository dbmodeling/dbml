//! DDL statement emitters for schemas, tables, constraints, comments, and indexes.

use super::dialect::SqlDialect;
use super::graph::fk_child_parent;
use super::types::{
    write_column_type, write_default_literal, write_qualified_ident, write_single_ident,
    write_sql_string,
};
use schema::{
    Endpoint, EnumDef, IndexColumn, IndexDef, Nullability, Ref, RefAction, Schema, Table,
};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

pub(super) fn emit_schemas(out: &mut String, schema: &Schema, dialect: SqlDialect) {
    if !matches!(dialect, SqlDialect::Postgres | SqlDialect::SqlServer) {
        return;
    }
    let schemas: BTreeSet<&str> = schema
        .tables
        .iter()
        .filter_map(|t| t.schema.as_deref())
        .chain(schema.enums.iter().filter_map(|e| e.schema.as_deref()))
        .filter(|s| !s.is_empty())
        .collect();
    if schemas.is_empty() {
        return;
    }
    out.push('\n');
    for s in schemas {
        match dialect {
            SqlDialect::Postgres => {
                out.push_str("CREATE SCHEMA IF NOT EXISTS ");
                write_single_ident(out, s, dialect);
                out.push_str(";\n");
            }
            SqlDialect::SqlServer => {
                out.push_str("IF SCHEMA_ID(N");
                write_sql_string(out, s);
                out.push_str(") IS NULL EXEC(N'CREATE SCHEMA ");
                write_single_ident(out, s, dialect);
                out.push_str("');\n");
            }
            _ => {}
        }
    }
}

pub(super) fn emit_table_comments(out: &mut String, table: &Table, dialect: SqlDialect) {
    if !matches!(dialect, SqlDialect::Postgres | SqlDialect::Oracle) {
        return;
    }
    if let Some(note) = &table.note {
        out.push_str("COMMENT ON TABLE ");
        write_qualified_ident(out, table.schema.as_deref(), &table.name, dialect);
        out.push_str(" IS ");
        write_sql_string(out, note);
        out.push_str(";\n");
    }
    for col in &table.columns {
        if let Some(note) = &col.note {
            out.push_str("COMMENT ON COLUMN ");
            write_qualified_ident(out, table.schema.as_deref(), &table.name, dialect);
            out.push('.');
            write_single_ident(out, &col.name, dialect);
            out.push_str(" IS ");
            write_sql_string(out, note);
            out.push_str(";\n");
        }
    }
}

fn begin_table_item(out: &mut String, first: &mut bool) {
    if *first {
        *first = false;
    } else {
        out.push_str(",\n");
    }
    out.push_str("  ");
}

pub(super) fn write_create_table(
    out: &mut String,
    table: &Table,
    enums: &BTreeMap<&str, &EnumDef>,
    inline_fks: &[&Ref],
    dialect: SqlDialect,
) {
    out.push_str("CREATE TABLE ");
    write_qualified_ident(out, table.schema.as_deref(), &table.name, dialect);
    out.push_str(" (\n");

    let pk_count = table.columns.iter().filter(|c| c.pk).count();
    let composite_pk_index = table
        .indexes
        .iter()
        .find(|ix| ix.pk && ix.columns.len() > 1);
    let inline_single_pk = pk_count == 1 && composite_pk_index.is_none();
    let mut first = true;

    for col in &table.columns {
        begin_table_item(out, &mut first);
        write_single_ident(out, &col.name, dialect);
        out.push(' ');
        let enum_def = enums.get(col.ty.as_str()).copied();
        write_column_type(out, &col.name, &col.ty, enum_def, dialect);

        if col.increment {
            match dialect {
                SqlDialect::Postgres | SqlDialect::Oracle => {
                    out.push_str(" GENERATED BY DEFAULT AS IDENTITY");
                }
                SqlDialect::Mysql => out.push_str(" AUTO_INCREMENT"),
                SqlDialect::SqlServer => out.push_str(" IDENTITY(1,1)"),
                SqlDialect::Sqlite => {}
            }
        }
        // Emit DEFAULT before inline constraints (required by Oracle: DEFAULT must precede NOT NULL).
        if let Some(def) = col.default_value.as_deref() {
            out.push_str(" DEFAULT ");
            write_default_literal(out, def, dialect);
        }
        if inline_single_pk && col.pk {
            out.push_str(" PRIMARY KEY");
            if dialect == SqlDialect::Sqlite && col.increment {
                out.push_str(" AUTOINCREMENT");
            }
        }
        if col.not_null && !col.pk {
            out.push_str(" NOT NULL");
        } else if col.nullability == Nullability::Nullable && !col.pk {
            out.push_str(" NULL");
        }
        if col.unique && !col.pk {
            out.push_str(" UNIQUE");
        }
        if dialect == SqlDialect::Mysql
            && let Some(note) = &col.note
        {
            out.push_str(" COMMENT ");
            write_sql_string(out, note);
        }
    }

    if pk_count > 1 {
        begin_table_item(out, &mut first);
        out.push_str("PRIMARY KEY (");
        let mut first_pk = true;
        for c in table.columns.iter().filter(|c| c.pk) {
            if !first_pk {
                out.push_str(", ");
            }
            first_pk = false;
            write_single_ident(out, &c.name, dialect);
        }
        out.push(')');
    } else if let Some(ix) = composite_pk_index {
        begin_table_item(out, &mut first);
        out.push_str("PRIMARY KEY (");
        write_index_cols(out, ix, dialect);
        out.push(')');
    }

    for (idx, r) in inline_fks.iter().enumerate() {
        let (child, parent) = fk_child_parent(r);
        begin_table_item(out, &mut first);
        out.push_str("CONSTRAINT ");
        write_fk_constraint_name(out, &child.table, child.primary_column(), idx + 1, dialect);
        write_fk_body(out, child, parent, r, dialect);
    }

    if dialect == SqlDialect::Mysql {
        out.push_str("\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
        if let Some(note) = &table.note {
            out.push_str(" COMMENT=");
            write_sql_string(out, note);
        }
        out.push_str(";\n");
    } else {
        out.push_str("\n);\n");
    }
}

fn write_fk_body(
    out: &mut String,
    child: &Endpoint,
    parent: &Endpoint,
    r: &Ref,
    dialect: SqlDialect,
) {
    out.push_str(" FOREIGN KEY (");
    for (i, c) in child.cols().iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        write_single_ident(out, c, dialect);
    }
    out.push_str(") REFERENCES ");
    write_qualified_ident(out, parent.schema.as_deref(), &parent.table, dialect);
    out.push('(');
    for (i, c) in parent.cols().iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        write_single_ident(out, c, dialect);
    }
    fk_close_with_actions(out, r, dialect);
}

pub(super) fn write_alter_fk(out: &mut String, r: &Ref, idx: usize, dialect: SqlDialect) {
    let (child, parent) = fk_child_parent(r);
    out.push_str("ALTER TABLE ");
    write_qualified_ident(out, child.schema.as_deref(), &child.table, dialect);
    out.push_str(" ADD CONSTRAINT ");
    write_fk_constraint_name(out, &child.table, child.primary_column(), idx, dialect);
    write_fk_body(out, child, parent, r, dialect);
    out.push_str(";\n");
}

fn write_fk_constraint_name(
    out: &mut String,
    table: &str,
    col: &str,
    idx: usize,
    dialect: SqlDialect,
) {
    let mut name = String::with_capacity(4 + table.len() + col.len() + 6);
    name.push_str("fk_");
    for ch in table.chars() {
        name.push(if ch == '.' { '_' } else { ch });
    }
    name.push('_');
    for ch in col.chars() {
        name.push(if ch == '.' { '_' } else { ch });
    }
    let _ = write!(name, "_{idx}");
    write_single_ident(out, &name, dialect);
}

fn fk_close_with_actions(out: &mut String, r: &Ref, dialect: SqlDialect) {
    out.push(')');
    write_ref_actions(out, r, dialect);
}

fn write_ref_actions(out: &mut String, r: &Ref, dialect: SqlDialect) {
    if let Some(del) = r.on_delete {
        match (dialect, del) {
            (SqlDialect::Oracle, RefAction::NoAction | RefAction::Restrict) => {}
            (SqlDialect::Oracle, RefAction::SetDefault) => {
                out.push_str(" /* ON DELETE SET DEFAULT not supported in Oracle */");
            }
            (SqlDialect::SqlServer, RefAction::Restrict) => {
                out.push_str(" ON DELETE NO ACTION");
            }
            _ => {
                out.push_str(" ON DELETE ");
                out.push_str(&del.as_dbml_str().to_ascii_uppercase());
            }
        }
    }
    if let Some(upd) = r.on_update {
        match dialect {
            SqlDialect::Oracle => {
                let _ = write!(
                    out,
                    " /* ON UPDATE {} not supported in Oracle */",
                    upd.as_dbml_str().to_ascii_uppercase()
                );
            }
            SqlDialect::SqlServer if upd == RefAction::Restrict => {
                out.push_str(" ON UPDATE NO ACTION");
            }
            _ => {
                out.push_str(" ON UPDATE ");
                out.push_str(&upd.as_dbml_str().to_ascii_uppercase());
            }
        }
    }
}

pub(super) fn write_create_index(
    out: &mut String,
    table: &Table,
    ix: &IndexDef,
    idx: usize,
    dialect: SqlDialect,
) {
    out.push_str(if ix.unique {
        "CREATE UNIQUE INDEX "
    } else {
        "CREATE INDEX "
    });
    let mut default_name = String::with_capacity(16 + table.name.len());
    let _ = write!(default_name, "idx_{}_{}", table.name.replace('.', "_"), idx);
    let name = ix.name.as_deref().unwrap_or(&default_name);
    write_single_ident(out, name, dialect);
    out.push_str(" ON ");
    write_qualified_ident(out, table.schema.as_deref(), &table.name, dialect);
    if dialect == SqlDialect::Postgres
        && let Some(ity) = ix.index_type
    {
        out.push_str(" USING ");
        out.push_str(ity.as_sql_str());
    }
    out.push_str(" (");
    write_index_cols(out, ix, dialect);
    out.push(')');
    if dialect == SqlDialect::Mysql
        && let Some(ity) = ix.index_type
    {
        out.push_str(" USING ");
        out.push_str(ity.as_sql_str());
    }
    out.push_str(";\n");
}

fn write_index_cols(out: &mut String, ix: &IndexDef, dialect: SqlDialect) {
    for (i, c) in ix.columns.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        match c {
            IndexColumn::Column(name) => write_single_ident(out, name, dialect),
            IndexColumn::Expression(expr) => {
                out.push('(');
                out.push_str(expr);
                out.push(')');
            }
        }
    }
}
