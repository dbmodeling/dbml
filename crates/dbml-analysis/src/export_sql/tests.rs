use super::*;

const SAMPLE: &str = "\
Enum role {
  admin
  member
}

Table users {
  id int [pk, increment]
  email varchar(120) [unique, not null]
  role role [not null, default: 'member']
  active bool [default: true]
  indexes {
    email [name: 'idx_users_email']
  }
}

Table posts {
  id int [pk]
  user_id int [not null, ref: > users.id, delete: cascade, update: no action]
}
";

#[test]
fn sql_dialect_parses_all_five_dialects_case_insensitively() {
    assert_eq!("Postgres".parse::<SqlDialect>(), Ok(SqlDialect::Postgres));
    assert_eq!("mysql".parse::<SqlDialect>(), Ok(SqlDialect::Mysql));
    assert_eq!("SQLite".parse::<SqlDialect>(), Ok(SqlDialect::Sqlite));
    assert_eq!("mssql".parse::<SqlDialect>(), Ok(SqlDialect::SqlServer));
    assert_eq!("oracle".parse::<SqlDialect>(), Ok(SqlDialect::Oracle));
    assert!("bogus".parse::<SqlDialect>().is_err());
}

#[test]
fn exports_postgres_enums_fks_and_indexes() {
    let sql = export_sql_ddl(SAMPLE, SqlDialect::Postgres);
    assert!(sql.contains("CREATE TYPE \"role\" AS ENUM ('admin', 'member');"));
    assert!(sql.contains("\"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
    assert!(sql.contains("\"active\" BOOLEAN DEFAULT TRUE"));
    assert!(sql.contains("ON DELETE CASCADE ON UPDATE NO ACTION"));
    assert!(sql.contains("CREATE INDEX \"idx_users_email\" ON \"users\" (\"email\");"));
}

#[test]
fn exports_mysql_backticks_and_inline_enum() {
    let sql = export_sql_ddl(SAMPLE, SqlDialect::Mysql);
    assert!(sql.contains("CREATE TABLE `users`"));
    assert!(sql.contains("`id` INT AUTO_INCREMENT PRIMARY KEY"));
    assert!(sql.contains("`role` ENUM('admin', 'member') DEFAULT 'member' NOT NULL"));
    assert!(sql.contains("`active` TINYINT(1) DEFAULT TRUE"));
    assert!(sql.contains(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"));
}

#[test]
fn exports_sqlite_inline_fks_and_check_enum() {
    let sql = export_sql_ddl(SAMPLE, SqlDialect::Sqlite);
    assert!(sql.contains("PRAGMA foreign_keys = ON;"));
    assert!(sql.contains("\"id\" INTEGER PRIMARY KEY AUTOINCREMENT"));
    assert!(sql.contains("CHECK (\"role\" IN ('admin', 'member'))"));
    assert!(sql.contains("\"active\" INTEGER DEFAULT 1"));
    assert!(sql.contains(
        "CONSTRAINT \"fk_posts_user_id_1\" FOREIGN KEY (\"user_id\") REFERENCES \"users\"(\"id\")"
    ));
    assert!(!sql.contains("ALTER TABLE"));
}

#[test]
fn exports_sqlserver_brackets_identity_and_types() {
    let sql = export_sql_ddl(SAMPLE, SqlDialect::SqlServer);
    assert!(sql.contains("CREATE TABLE [users]"));
    assert!(sql.contains("[id] INT IDENTITY(1,1) PRIMARY KEY"));
    assert!(sql.contains("[email] NVARCHAR(120) NOT NULL UNIQUE"));
    assert!(sql.contains("[active] BIT DEFAULT 1"));
}

#[test]
fn exports_oracle_varchar2_number_and_omits_on_update() {
    let sql = export_sql_ddl(SAMPLE, SqlDialect::Oracle);
    assert!(sql.contains("\"id\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
    assert!(sql.contains("\"email\" VARCHAR2(120) NOT NULL UNIQUE"));
    assert!(sql.contains("DEFAULT 'member' NOT NULL"));
    assert!(sql.contains("\"active\" NUMBER(1) DEFAULT 1"));
    assert!(sql.contains("ON DELETE CASCADE /* ON UPDATE NO ACTION not supported in Oracle */"));
}

#[test]
fn handles_qualified_table_names_block_comments_and_oracle_json_set_default() {
    let src = "\
/* block comment */
Enum status {
  open // inline comment
  closed [note: 'done']
}
Table \"public.items\" {
  id int [pk]
  payload jsonb
  st status [not null, default: 'open']
  parent_id int [ref: > \"public.items\".id, delete: set default]
}
";
    let pg = export_sql_ddl(src, SqlDialect::Postgres);
    assert!(pg.contains("CREATE TABLE \"public\".\"items\""), "{pg}");
    assert!(
        pg.contains("\"st\" \"status\" DEFAULT 'open' NOT NULL"),
        "{pg}"
    );

    let ora = export_sql_ddl(src, SqlDialect::Oracle);
    assert!(
        ora.contains("\"payload\" CLOB CHECK (\"payload\" IS JSON)"),
        "{ora}"
    );
    assert!(
        ora.contains("/* ON DELETE SET DEFAULT not supported in Oracle */"),
        "{ora}"
    );
}

#[test]
fn topological_sort_orders_parent_before_child_and_breaks_cycles_with_alter_table() {
    let ordered_src = "Table child {\n  id int [pk]\n  parent_id int [ref: > parent.id]\n}\nTable parent {\n  id int [pk]\n}\n";
    let sql = export_sql_ddl(ordered_src, SqlDialect::Postgres);
    let p_pos = sql.find("CREATE TABLE \"parent\"").unwrap();
    let c_pos = sql.find("CREATE TABLE \"child\"").unwrap();
    assert!(p_pos < c_pos, "{sql}");

    let cycle_src = "Table a {\n  id int [pk]\n  b_id int [ref: > b.id]\n}\nTable b {\n  id int [pk]\n  a_id int [ref: > a.id]\n}\n";
    let cycle_sql = export_sql_ddl(cycle_src, SqlDialect::Postgres);
    assert!(cycle_sql.contains("ALTER TABLE"), "{cycle_sql}");
}

#[test]
fn exports_schemas_aliases_composite_fks_notes_null_and_typed_indexes() {
    let src = "\
Table auth.users as u {
  id int [pk]
  org_id int [not null]
  bio text [null, note: 'Bio text']
  Note: 'User accounts'
}
Table public.orders {
  id int [pk]
  org_id int [not null]
  user_id int [not null]
  email varchar(120)
  indexes {
    (`lower(email)`) [type: hash, name: 'idx_orders_email_lower']
  }
}
Ref: public.orders.(org_id, user_id) > u.(org_id, id) [delete: cascade]
";
    let pg = export_sql_ddl(src, SqlDialect::Postgres);
    assert!(pg.contains("CREATE SCHEMA IF NOT EXISTS \"auth\";"), "{pg}");
    assert!(
        pg.contains("CREATE SCHEMA IF NOT EXISTS \"public\";"),
        "{pg}"
    );
    assert!(
        pg.contains("COMMENT ON TABLE \"auth\".\"users\" IS 'User accounts';"),
        "{pg}"
    );
    assert!(
        pg.contains("COMMENT ON COLUMN \"auth\".\"users\".\"bio\" IS 'Bio text';"),
        "{pg}"
    );
    assert!(
        pg.contains(
            "CONSTRAINT \"fk_orders_org_id_1\" FOREIGN KEY (\"org_id\", \"user_id\") REFERENCES \"auth\".\"users\"(\"org_id\", \"id\") ON DELETE CASCADE"
        ),
        "{pg}"
    );
    assert!(
        pg.contains(
            "CREATE INDEX \"idx_orders_email_lower\" ON \"public\".\"orders\" USING hash ((lower(email)));"
        ),
        "{pg}"
    );

    let tsql = export_sql_ddl(src, SqlDialect::SqlServer);
    assert!(
        tsql.contains("IF SCHEMA_ID(N'auth') IS NULL EXEC(N'CREATE SCHEMA [auth]');"),
        "{tsql}"
    );
    assert!(tsql.contains("[bio] NVARCHAR(MAX) NULL"), "{tsql}");

    let mysql = export_sql_ddl(src, SqlDialect::Mysql);
    assert!(
        mysql.contains("`bio` TEXT NULL COMMENT 'Bio text'"),
        "{mysql}"
    );
    assert!(mysql.contains("COMMENT='User accounts'"), "{mysql}");
}
