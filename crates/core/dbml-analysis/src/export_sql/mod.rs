#[cfg(test)]
mod tests;

pub use dialect::{SqlDialect, SqlExportError};

use crate::analyze;
use emit::{
    emit_schemas, emit_table_comments, write_alter_fk, write_create_index, write_create_table,
};
use graph::{fk_child_endpoint, topological_order};
use schema::{EnumDef, Ref, RefKind};
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;
use types::{write_qualified_ident, write_sql_string};

/// Generates DDL only when the source passes DBML validation.
///
/// # Errors
///
/// Returns an error for invalid DBML or schema names that SQLite cannot represent.
pub fn try_export_sql_ddl(source: &str, dialect: SqlDialect) -> Result<String, SqlExportError> {
    if let Some(diagnostic) = crate::lint(source)
        .into_iter()
        .find(|d| d.severity == crate::Severity::Error)
    {
        return Err(SqlExportError::InvalidSource(diagnostic.message));
    }
    let schema = analyze(source);
    if dialect == SqlDialect::Sqlite
        && let Some(name) = schema
            .tables
            .iter()
            .find_map(|table| table.schema.as_deref())
    {
        return Err(SqlExportError::SqliteSchema(name.to_owned()));
    }
    Ok(export_schema_sql_ddl(source, dialect, &schema))
}

/// Generates SQL DDL from DBML `source` for the requested `dialect`.
#[must_use]
pub fn export_sql_ddl(source: &str, dialect: SqlDialect) -> String {
    export_schema_sql_ddl(source, dialect, &analyze(source))
}

fn export_schema_sql_ddl(source: &str, dialect: SqlDialect, schema: &schema::Schema) -> String {
    let mut out = String::with_capacity(source.len().saturating_mul(2));

    let _ = writeln!(out, "-- Generated by DB Modeling ({dialect})");

    if dialect == SqlDialect::Sqlite {
        out.push_str("\nPRAGMA foreign_keys = ON;\n");
    }

    if let Some(proj_note) = &schema.project_note {
        let _ = writeln!(out, "-- Project: {proj_note}");
    }

    emit_schemas(&mut out, schema, dialect);

    let enum_map: BTreeMap<&str, &EnumDef> =
        schema.enums.iter().map(|e| (e.name.as_str(), e)).collect();

    if dialect == SqlDialect::Postgres && !schema.enums.is_empty() {
        out.push('\n');
        for e in &schema.enums {
            out.push_str("CREATE TYPE ");
            write_qualified_ident(&mut out, e.schema.as_deref(), &e.name, dialect);
            out.push_str(" AS ENUM (");
            for (idx, v) in e.values.iter().enumerate() {
                if idx > 0 {
                    out.push_str(", ");
                }
                write_sql_string(&mut out, &v.name, dialect);
            }
            out.push_str(");\n");
        }
    }

    let (ordered_tables, deferred_refs) = topological_order(schema);
    let mut inline_refs_by_table: HashMap<(Option<&str>, &str), Vec<&Ref>> = HashMap::new();
    let mut m2m_notes: Vec<&Ref> = Vec::new();
    let mut cycle_refs: Vec<&Ref> = Vec::new();

    if dialect == SqlDialect::Sqlite {
        for r in &schema.refs {
            if r.kind == RefKind::ManyToMany {
                m2m_notes.push(r);
            } else {
                let child = fk_child_endpoint(r);
                inline_refs_by_table
                    .entry((child.schema.as_deref(), child.table.as_str()))
                    .or_default()
                    .push(r);
            }
        }
    } else {
        for r in deferred_refs {
            if r.kind == RefKind::ManyToMany {
                m2m_notes.push(r);
            } else {
                cycle_refs.push(r);
            }
        }
        let deferred_ptrs: BTreeSet<usize> = cycle_refs
            .iter()
            .map(|&r| std::ptr::from_ref(r) as usize)
            .collect();
        for r in &schema.refs {
            if r.kind == RefKind::ManyToMany {
                m2m_notes.push(r);
            } else if !deferred_ptrs.contains(&(std::ptr::from_ref(r) as usize)) {
                let child = fk_child_endpoint(r);
                inline_refs_by_table
                    .entry((child.schema.as_deref(), child.table.as_str()))
                    .or_default()
                    .push(r);
            }
        }
    }

    for table in &ordered_tables {
        out.push('\n');
        write_create_table(
            &mut out,
            table,
            &enum_map,
            inline_refs_by_table
                .get(&(table.schema.as_deref(), table.name.as_str()))
                .map_or(&[][..], Vec::as_slice),
            dialect,
        );
        emit_table_comments(&mut out, table, dialect);
    }

    if !cycle_refs.is_empty() {
        out.push('\n');
        for (idx, r) in cycle_refs.iter().enumerate() {
            write_alter_fk(&mut out, r, idx + 1, dialect);
        }
    }

    let mut wrote_index_header = false;
    let mut global_idx = 0usize;
    for table in &ordered_tables {
        for ix in &table.indexes {
            global_idx += 1;
            if ix.pk {
                continue;
            }
            if !wrote_index_header {
                out.push('\n');
                wrote_index_header = true;
            }
            write_create_index(&mut out, table, ix, global_idx, dialect);
        }
    }

    if !m2m_notes.is_empty() {
        out.push('\n');
        for r in m2m_notes {
            let _ = writeln!(
                out,
                "-- Many-to-many relation {}.{} <> {}.{} requires a junction table",
                r.from.table,
                r.from.primary_column(),
                r.to.table,
                r.to.primary_column()
            );
        }
    }

    out
}
