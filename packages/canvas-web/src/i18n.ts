const english = new Map(translations);
let language: Language = 'pt-BR';

export function systemLanguage(value: string): Language {
  return value.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}

export function setLanguage(value: Language): void { language = value; }
export function t(key: string, ...values: (string | number)[]): string {
  let result = language === 'en' ? english.get(key) ?? key : key;
  for (const value of values) result = result.replace('{}', String(value));
  return result;
}


/** Localiza mensagens conhecidas do lint preservando os identificadores DBML. */
export function diagnosticMessage(message: string): string {
  if (language === 'en') return message;
  switch (message) {
    case 'Disconnected; reconnect and save again':
    case 'Connection lost; reconnect and save again':
      return 'Conexão interrompida. Reconecte e salve novamente.';
    case 'Active file changed; reload or reconcile changes':
    case 'Document changed outside this editor; reload or reconcile changes':
      return 'O documento mudou fora desta tela. Exporte suas alterações antes de recarregar.';
    case 'Table without a name': return 'Tabela sem nome';
    case 'Expected `Ref: table.column > table.column`': return 'Esperado `Ref: table.column > table.column`';
  }
  const unclosed = /^Table `(.+)` was not closed with `}`$/.exec(message);
  if (unclosed) return `A tabela \`${unclosed[1]}\` deve terminar com \`}\``;
  const duplicate = /^Duplicate table `(.+)`$/.exec(message);
  if (duplicate) return `Tabela duplicada \`${duplicate[1]}\``;
  return message;
}

export function connectionHint(message: string, sqlite: boolean): string {
  if (/authenticat|login failed|access denied for user|password|28p01|18456/i.test(message)) {
    return t('O banco recusou a autenticação. Confira o usuário e a senha.');
  }
  if (/timeout|timed? out|connection refused|econnrefused|could not resolve/i.test(message)) {
    return t('O banco não respondeu. Confira o host, a porta e se o serviço está rodando.');
  }
  if (/could not read the catalog/i.test(message)) {
    return t('Não foi possível ler o esquema. Verifique as permissões de leitura do catálogo.');
  }
  return sqlite
    ? t('Não foi possível abrir o banco SQLite. Confira o caminho e as permissões do arquivo.')
    : t('Não foi possível conectar. Confira os dados da conexão e tente novamente.');
}
